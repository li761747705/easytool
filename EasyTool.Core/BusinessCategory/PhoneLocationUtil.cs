        /// <summary>
        /// 获取手机号归属地信息
        /// </summary>
        /// <param name="phone">手机号（11位）</param>
        /// <returns>归属地信息，未找到返回null</returns>
        public static PhoneLocationInfo? GetLocation(string? phone)
        {
            if (string.IsNullOrWhiteSpace(phone))
                return null;

            // 清理手机号
            phone = phone.Trim();

            if (phone.Length != 11)
                return null;

            // 尝试匹配前7位号段
            string segment7 = phone.Substring(0, 7);
            if (PhoneSegments.TryGetValue(segment7, out var info))
                return info;

            // 尝试匹配前6位
            string segment6 = phone.Substring(0, 6);
            info = FindByPrefix(segment6);
            if (info != null)
                return info;

            // 尝试匹配前5位
            string segment5 = phone.Substring(0, 5);
            info = FindByPrefix(segment5);
            if (info != null)
                return info;

            // 尝试匹配前4位
            string segment4 = phone.Substring(0, 4);
            info = FindByPrefix(segment4);
            if (info != null)
                return info;

            // 尝试匹配前3位
            string segment3 = phone.Substring(0, 3);
            info = FindByPrefix(segment3);
            if (info != null)
                return info;

            // 至少返回运营商信息
            if (CarrierByPrefix.TryGetValue(segment3, out var carrier))
            {
                return new PhoneLocationInfo
                {
                    Segment = segment3,
                    Carrier = carrier,
                    Province = "未知",
                    City = "未知"
                };
            }

            return null;
        }

        /// <summary>
        /// 根据前缀查找归属地
        /// </summary>
        private static PhoneLocationInfo? FindByPrefix(string prefix)
        {
            foreach (var key in PhoneSegments.Keys)
            {
                if (key.StartsWith(prefix))
                    return PhoneSegments[key];
            }
            return null;
        }

