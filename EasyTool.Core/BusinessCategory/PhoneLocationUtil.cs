        /// <summary>
        /// 验证手机号格式
        /// </summary>
        /// <param name="phone">手机号</param>
        /// <returns>是否有效</returns>
        public static bool IsValidFormat(string? phone)
        {
            if (string.IsNullOrWhiteSpace(phone))
                return false;

            phone = phone.Trim();
            if (phone.Length != 11)
                return false;

            foreach (var c in phone)
            {
                if (!char.IsDigit(c))
                    return false;
            }

            // 验证前3位是否为有效运营商号段
            string prefix3 = phone.Substring(0, 3);
            return CarrierByPrefix.ContainsKey(prefix3);
        }

        /// <summary>
        /// 获取完整归属地描述
        /// </summary>
        /// <param name="phone">手机号</param>
        /// <returns>归属地描述（运营商 省份 城市）</returns>
        public static string? GetFullLocation(string? phone)
        {
            var info = GetLocation(phone);
            if (info == null)
                return null;

            if (info.Province == "未知" || info.City == "未知")
                return info.Carrier;

            return $"{info.Carrier} {info.Province} {info.City}";
        }

